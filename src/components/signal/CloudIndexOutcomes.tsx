import { useEffect, useState } from "react";
import { Cloud, RefreshCw } from "lucide-react";
type OutcomeRow={
 alert_id:string;symbol:string;strategy:string;direction:string;timeframe:string;signal_time:number;
 status:"OPEN"|"WON"|"LOST"|"EXPIRED";target:string|null;closed_at:number|null;checked_at:number;
 entry:number;stop_loss:number;tp1:number;tp2:number;
};
const FALLBACK_URL="https://tradepulse-index-alert-service.davidmwesigwa71.workers.dev";
function summarize(rows:OutcomeRow[]) {
 const completed=rows.filter(x=>x.closed_at!==null&&(x.status==="WON"||x.status==="LOST"));
 const wins=completed.filter(x=>x.status==="WON").length;
 const losses=completed.length-wins;
 const groups=new Map<string,{label:string;wins:number;losses:number}>();
 for(const x of completed){
   const key=x.symbol+" · "+x.strategy;
   const prev=groups.get(key)??{label:key,wins:0,losses:0};
   if(x.status==="WON")prev.wins++;
   else prev.losses++;
   groups.set(key,prev);
 }
 return {wins,losses,resolved:completed.length,groups:[...groups.values()].sort((a,b)=>(b.losses-a.losses)||((b.wins+b.losses)-(a.wins+a.losses)))};
}
/** Public index-alert follow-ups only, separate from signed-in account tracking. */
export function CloudIndexOutcomes(){
 const [rows,setRows]=useState<OutcomeRow[]>([]);
 const [status,setStatus]=useState("Loading background index results…");
 const [lastChecked,setLastChecked]=useState<number|null>(null);
 const source=(import.meta.env["VITE_INDEX_ALERTS_URL"] as string|undefined)||FALLBACK_URL;
 useEffect(()=>{
  const controller=new AbortController();
  const update=async()=>{
   try {
    const base=new URL(source);
    const url=new URL("/outcomes",base);
    const res=await fetch(url.toString(),{signal:controller.signal,cache:"no-store"});
    if(!res.ok)throw Error(res.status===503?"Database migration / Worker update still pending":"Background outcome feed unavailable ("+res.status+")");
    const payload:unknown=await res.json();
    if(!payload||typeof payload!=="object"||!("outcomes" in payload)||!Array.isArray(payload.outcomes))throw Error("Invalid outcome feed");
    const found=(payload.outcomes as unknown[]).filter((value):value is OutcomeRow=>{
     if(!value||typeof value!=="object")return false;
     const x=value as Partial<OutcomeRow>;
     return typeof x.alert_id==="string"&&typeof x.symbol==="string"&&typeof x.strategy==="string"&&
      (x.status==="OPEN"||x.status==="WON"||x.status==="LOST"||x.status==="EXPIRED")&&
      typeof x.signal_time==="number"&&typeof x.checked_at==="number"&&
      typeof x.entry==="number"&&typeof x.stop_loss==="number"&&typeof x.tp1==="number"&&typeof x.tp2==="number";
    });
    if(!controller.signal.aborted){setRows(found);setStatus("Connected to server-side index outcome feed");setLastChecked(Date.now());}
   }catch(e){if(!controller.signal.aborted)setStatus(e instanceof Error?e.message:"Outcome service unavailable");}
  };
  void update();const interval=setInterval(()=>void update(),60000);
  return ()=>{controller.abort();clearInterval(interval);};
 },[source]);
 const stats=summarize(rows);
 return <section className="mt-6 rounded-xl border border-primary/30 bg-card/70 p-4 sm:p-5" aria-label="Background index outcome tracking">
  <div className="flex flex-wrap items-start justify-between gap-3">
   <div><h2 className="flex items-center gap-2 font-display text-lg font-bold"><Cloud className="h-5 w-5 text-primary"/> CLOUD INDEX ALERT FOLLOW-UP</h2>
    <p className="mt-1 text-xs text-muted-foreground">Follows index alerts generated by the independent Cloudflare Worker while the website is closed. These are public signal outcomes, separate from your personal tracked-signal statistics.</p>
   </div>
   <span className="flex items-center gap-1 text-xs text-muted-foreground"><RefreshCw className="h-3 w-3"/> 60-second refresh</span>
  </div>
  <p role="status" className="mt-3 text-xs text-muted-foreground">{status}{lastChecked?" · "+new Date(lastChecked).toLocaleTimeString():""}</p>
  <div className="mt-3 grid grid-cols-2 gap-2 sm:grid-cols-4">
   {([["Total monitored",rows.length],["Resolved",stats.resolved],["Won",stats.wins],["Lost",stats.losses]] as const).map(([name,val])=>
    <div key={name} className="rounded-lg border border-border bg-background/50 p-3"><p className="text-[10px] uppercase text-muted-foreground">{name}</p><p className="mt-1 font-display text-xl font-bold">{val}</p></div>)}
  </div>
  <div className="mt-3 max-h-56 space-y-2 overflow-y-auto">
   {stats.groups.length===0?<p className="text-xs text-muted-foreground">No completed background index outcomes have been confirmed yet.</p>:
    stats.groups.slice(0,15).map(g=><div key={g.label} className="flex flex-wrap justify-between gap-2 rounded border border-border p-2 text-xs">
     <strong>{g.label}</strong><span>{g.wins} won · {g.losses} lost · {g.wins+g.losses} resolved</span>
    </div>)}
  </div>
  <p className="mt-3 text-xs text-amber-600 dark:text-amber-300">Historical candle-based labels only, not exchange fills or realized P&amp;L. Telegram/background outcomes are not yet merged into personal pair/strategy avoidance rules. No fake results are inserted if the backend is not deployed.</p>
 </section>;
}
